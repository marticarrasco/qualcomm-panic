# %% [markdown]
# # 2. Fine-Tune `Qwen/Qwen3.5-0.8B` with LoRA (Exact Match for `llama-server --jinja --reasoning off`)
#
# Critical architectural detail for `Qwen3.5-0.8B` on `llama-server`:
# When `llama-server` runs with `--jinja --reasoning off --reasoning-budget 0`, it prefills every
# assistant turn with `<|im_start|>assistant\n<think>\n\n</think>\n\n`.
# Therefore, we construct each training sequence with that exact prefix and mask `labels = -100`
# on all tokens up to and including `<think>\n\n</think>\n\n`, training ONLY on the Python procedure!

# %%
import hashlib
import json
import os
import subprocess
import torch
from torch.utils.data import Dataset
from transformers import (
    AutoModelForCausalLM,
    AutoTokenizer,
    Trainer,
    TrainingArguments,
)
from peft import LoraConfig, get_peft_model

MODEL_ID = "Qwen/Qwen3.5-0.8B"
TRAIN_JSONL = "sft_train_pot.jsonl"  # Adjust path if mounted under /kaggle/input/...
OUTPUT_DIR = "qwen35_kang_pot_lora"
MERGED_DIR = "qwen35_kang_pot_merged"
GGUF_OUT = "Qwen_Qwen3.5-0.8B-KangPoT-Q8_0.gguf"
LLAMA_CPP_COMMIT = "2cbe0ec429b849a88664e0f62388fc92a5abd699"
MAX_SEQ_LEN = 512


class KangPoTDataset(Dataset):
    """Tokenizes chat messages matching llama-server --jinja --reasoning off and masks prompt loss."""

    def __init__(self, path, tokenizer, max_len=MAX_SEQ_LEN):
        self.samples = []
        with open(path, encoding="utf-8") as f:
            raw_rows = [json.loads(line) for line in f if line.strip()]

        for row in raw_rows:
            msgs = row["messages"]
            sys_msg = msgs[0]["content"]
            user_msg = msgs[1]["content"]
            asst_msg = msgs[2]["content"]

            # Exact prefix generated by llama-server --jinja --reasoning off --reasoning-budget 0
            prompt_text = (
                f"<|im_start|>system\n{sys_msg}<|im_end|>\n"
                f"<|im_start|>user\n{user_msg}<|im_end|>\n"
                f"<|im_start|>assistant\n<think>\n\n</think>\n\n"
            )
            target_text = f"{asst_msg}<|im_end|>\n"

            prompt_ids = tokenizer.encode(prompt_text, add_special_tokens=False)
            target_ids = tokenizer.encode(target_text, add_special_tokens=False)

            input_ids = (prompt_ids + target_ids)[:max_len]
            labels = ([-100] * len(prompt_ids) + target_ids)[:max_len]
            if any(x != -100 for x in labels):
                self.samples.append({
                    "input_ids": input_ids,
                    "attention_mask": [1] * len(input_ids),
                    "labels": labels,
                })

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        return self.samples[idx]


def collate_fn(batch, pad_id):
    max_l = max(len(x["input_ids"]) for x in batch)
    input_ids, attn_mask, labels = [], [], []
    for x in batch:
        pad_n = max_l - len(x["input_ids"])
        input_ids.append(x["input_ids"] + [pad_id] * pad_n)
        attn_mask.append(x["attention_mask"] + [0] * pad_n)
        labels.append(x["labels"] + [-100] * pad_n)
    return {
        "input_ids": torch.tensor(input_ids, dtype=torch.long),
        "attention_mask": torch.tensor(attn_mask, dtype=torch.long),
        "labels": torch.tensor(labels, dtype=torch.long),
    }


def train_and_export():
    tokenizer = AutoTokenizer.from_pretrained(MODEL_ID, trust_remote_code=True)
    if tokenizer.pad_token_id is None:
        tokenizer.pad_token_id = tokenizer.eos_token_id

    dataset = KangPoTDataset(TRAIN_JSONL, tokenizer)
    print(f"Loaded {len(dataset)} tokenized training sequences (max_len={MAX_SEQ_LEN})")

    dtype = torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16
    model = AutoModelForCausalLM.from_pretrained(
        MODEL_ID,
        torch_dtype=dtype,
        device_map="auto",
        trust_remote_code=True,
    )

    lora_config = LoraConfig(
        r=16,
        lora_alpha=32,
        lora_dropout=0.05,
        bias="none",
        task_type="CAUSAL_LM",
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
    )
    model = get_peft_model(model, lora_config)
    model.print_trainable_parameters()

    training_args = TrainingArguments(
        output_dir=OUTPUT_DIR,
        num_train_epochs=3,
        per_device_train_batch_size=8,
        gradient_accumulation_steps=2,
        learning_rate=2e-4,
        lr_scheduler_type="cosine",
        warmup_ratio=0.05,
        weight_decay=0.01,
        logging_steps=20,
        save_strategy="epoch",
        bf16=(dtype == torch.bfloat16),
        fp16=(dtype == torch.float16),
        report_to="none",
        seed=42,
    )

    trainer = Trainer(
        model=model,
        args=training_args,
        train_dataset=dataset,
        data_collator=lambda b: collate_fn(b, tokenizer.pad_token_id),
    )
    trainer.train()

    print("Merging LoRA weights into base model...")
    merged = model.merge_and_unload()
    merged.save_pretrained(MERGED_DIR, safe_serialization=True)
    tokenizer.save_pretrained(MERGED_DIR)

    # Convert to GGUF Q8_0 using the exact Datathon llama.cpp commit
    if not os.path.exists("llama.cpp"):
        subprocess.run(["git", "clone", "https://github.com/ggml-org/llama.cpp.git"], check=True)
    subprocess.run(["git", "-C", "llama.cpp", "fetch", "--depth", "1", "origin", LLAMA_CPP_COMMIT], check=True)
    subprocess.run(["git", "-C", "llama.cpp", "checkout", LLAMA_CPP_COMMIT], check=True)

    subprocess.run([
        "python3", "llama.cpp/convert_hf_to_gguf.py",
        MERGED_DIR,
        "--outtype", "q8_0",
        "--outfile", GGUF_OUT,
    ], check=True)

    sha256 = hashlib.sha256(open(GGUF_OUT, "rb").read()).hexdigest()
    size_mb = os.path.getsize(GGUF_OUT) / (1024 * 1024)
    print("\n" + "=" * 65)
    print(f"SUCCESS! Exported {GGUF_OUT} ({size_mb:.1f} MB)")
    print(f"Update your config.env with:")
    print(f"LLM_MODEL_FILE={GGUF_OUT}")
    print(f"LLM_MODEL_SHA256={sha256}")
    print("=" * 65)


if __name__ == "__main__":
    train_and_export()
